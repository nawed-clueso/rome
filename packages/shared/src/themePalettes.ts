/** A theme with a light and a dark half, from two compact palettes. */
function pairedTheme(
  id: string,
  label: string,
  light: CompactPalette,
  dark: CompactPalette,
): ThemeDefinition {
  return {
    id,
    label,
    appearance: "dark",
    colors: paletteColors(T3_CODE_DARK_THEME_COLORS, dark),
    variants: { light: paletteColors(T3_CODE_LIGHT_THEME_COLORS, light) },
  };
}

