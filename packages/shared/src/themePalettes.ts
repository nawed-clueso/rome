/** The few colours a theme is made of; the rest of its roles follow from them. */
type CompactPalette = Readonly<{
  canvas: string;
  surface: string;
  raised: string;
  sidebar: string;
  text: string;
  muted: string;
  border: string;
  input: string;
  accent: string;
  accentFg: string;
  hover: string;
  active: string;
  selection: string;
  /** Search highlights, for palettes whose surfaces are too close to the standard yellow. */
  search?: Readonly<{
    background: string;
    foreground: string;
    active: string;
    activeForeground: string;
  }>;
}>;

function paletteColors(base: ThemeColors, p: CompactPalette): ThemeColors {
  return {
    ...base,
    canvas: p.canvas,
    chrome: p.canvas,
    toolbar: p.canvas,
    toolbarForeground: p.text,
    toolbarBorder: p.border,
    toolbarControl: p.raised,
    toolbarControlForeground: p.text,
    toolbarControlHover: p.hover,
    surface: p.surface,
    surfaceRaised: p.raised,
    surfaceOverlay: p.raised,
    text: p.text,
    textMuted: p.muted,
    border: p.border,
    input: p.input,
    focus: p.accent,
    accent: p.accent,
    accentForeground: p.accentFg,
    secondary: p.raised,
    secondaryForeground: p.text,
    muted: p.raised,
    mutedForeground: p.muted,
    placeholder: p.muted,
    secondaryLabel: p.muted,
    iconMuted: p.muted,
    update: p.accent,
    updateForeground: p.accent,
    updateSurface: p.active,
    accentSurface: p.active,
    accentSurfaceForeground: p.text,
    messageSurface: p.active,
    messageForeground: p.text,
    messageAction: p.accent,
    messageActionForeground: p.accentFg,
    messageActionHover: p.accent,
    codeBackground: p.surface,
    codeForeground: p.text,
    sidebar: p.sidebar,
    sidebarForeground: p.text,
    sidebarMutedForeground: p.muted,
    sidebarControlSurface: p.raised,
    sidebarRowHover: p.hover,
    sidebarRowActive: p.active,
    sidebarRowSelected: p.raised,
    sidebarBorder: p.border,
    terminalBackground: p.canvas,
    terminalForeground: p.text,
    terminalCursor: p.accent,
    terminalSelection: p.selection,
    terminalScrollbar: p.border,
    terminalScrollbarHover: p.input,
    ...(p.search
      ? {
          searchMatchBackground: p.search.background,
          searchMatchForeground: p.search.foreground,
          searchMatchActiveBackground: p.search.active,
          searchMatchActiveForeground: p.search.activeForeground,
        }
      : {}),
  };
}

